#!/usr/bin/env node
/**
 * Generate docs/ai-support-matrix.md from the live schema and the conversational authoring baseline.
 *
 *   pnpm --filter @citolab/prose-qti-node build && pnpm --filter @citolab/qti-ai-prosemirror build
 *   node scripts/ai-support-matrix.mjs            # writes the file
 *   node scripts/ai-support-matrix.mjs --check    # exits 1 when the committed file is stale
 *
 * Read off the artefacts, never hand-written: the schema comes from `@citolab/prose-qti-node`
 * (plain Node, no browser) and the annotations from the built `@citolab/qti-ai-prosemirror`. What
 * cannot be read off anything — intentional gaps and rendering caveats — is the short prose block
 * at the bottom, kept here so the matrix and its caveats travel together.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { createQtiSchema } from '../packages/prose-qti-node/dist/index.js';

import { BASELINE_VERSION, createCapabilities } from '../packages/qti-ai-prosemirror/dist/index.js';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'docs/ai-support-matrix.md');
const check = process.argv.includes('--check');

const schema = createQtiSchema();
const caps = createCapabilities(schema);
const catalog = readFileSync(resolve(root, 'pnpm-workspace.yaml'), 'utf8');
const componentVersions = [
  ...catalog.matchAll(/'(@qti-components\/[a-z-]+|@citolab\/qti-components)': '([^']+)'/g)
].map(m => `${m[1]}@${m[2]}`);

const interactions = Object.entries(caps.nodes)
  .filter(([, n]) => n.tag.endsWith('-interaction'))
  .sort(([a], [b]) => a.localeCompare(b));

const children = Object.entries(caps.nodes)
  .filter(([, n]) => n.tag.startsWith('qti-') && !n.tag.endsWith('-interaction') && Object.keys(n.attributes).length)
  .sort(([a], [b]) => a.localeCompare(b));

const yes = '✓';
const no = '–';

function attributeRows(node) {
  return Object.entries(node.attributes)
    .map(
      ([name, a]) =>
        `| \`${name}\` | \`${a.htmlName ?? no}\` | ${a.type}${a.nullable ? ' \\| null' : ''}${a.min !== undefined ? ` ≥ ${a.min}` : ''}${a.values ? ` (${a.values.join(', ')})` : ''} | ${a.editable ? yes : 'via ' + (name === 'class' ? 'vocabulary' : 'editor')} | ${a.description?.en ?? '_derived from schema default_'} |`
    )
    .join('\n');
}

function vocabularyRows(node) {
  if (!node.vocabulary.length) return '_No shared vocabulary for this node._';
  return [
    '| Group | Selection | Tokens | Rendering | Export |',
    '| --- | --- | --- | --- | --- |',
    ...node.vocabulary.map(
      g =>
        `| \`${g.id}\` | ${g.selection} | ${g.options.map(o => `\`${o.value}\``).join(', ')} | ${g.support.rendering === 'components' ? 'components' : '**unverified**'} | ${g.support.export} |`
    )
  ].join('\n');
}

const lines = [
  '# Conversational authoring support matrix',
  '',
  '<!-- Generated by scripts/ai-support-matrix.mjs. Do not edit by hand; run `pnpm ai:matrix`. -->',
  '',
  `Manifest version ${caps.version}, baseline ${BASELINE_VERSION}. Derived from \`createQtiSchema()\` with every interaction included.`,
  '',
  'Support is tracked per dimension:',
  '',
  '- **Schema**: the node and attribute exist in the editor schema and survive HTML ⇄ ProseMirror.',
  '- **Operation**: the agent may change it through a typed operation (`setAttributes` or `setVocabulary`). Identity and `class` are never edited directly.',
  '- **Rendering**: `components` means the pinned `@qti-components` packages reference the token; `unverified` means it is standard vocabulary the editor preserves and exports but no component stylesheet was found for it.',
  '- **Export**: shared vocabulary is standard QTI 3 and exports unchanged; attributes export through the item-export path.',
  '',
  `Pinned components: ${componentVersions.map(v => `\`${v}\``).join(', ')}.`,
  '',
  '## Interactions',
  '',
  '| Node | Tag | Attributes | Editable | Vocabulary groups | Rendering-unverified groups |',
  '| --- | --- | --- | --- | --- | --- |',
  ...interactions.map(([name, n]) => {
    const attrs = Object.values(n.attributes);
    return `| \`${name}\` | \`${n.tag}\` | ${attrs.length} | ${attrs.filter(a => a.editable).length} | ${n.vocabulary.length} | ${n.vocabulary.filter(g => g.support.rendering !== 'components').length} |`;
  }),
  '',
  ...interactions.flatMap(([name, n]) => [
    `### \`${name}\` (\`${n.tag}\`)`,
    '',
    `Content: \`${n.content}\``,
    '',
    '| Attribute | HTML | Type | Operation | Meaning |',
    '| --- | --- | --- | --- | --- |',
    attributeRows(n),
    '',
    vocabularyRows(n),
    ''
  ]),
  '## Child nodes with attributes',
  '',
  ...children.flatMap(([name, n]) => [
    `### \`${name}\` (\`${n.tag}\`)`,
    '',
    '| Attribute | HTML | Type | Operation | Meaning |',
    '| --- | --- | --- | --- | --- |',
    attributeRows(n),
    ''
  ]),
  '## Intentional gaps and limitations',
  '',
  '- **Not in the schema**: hotspot, graphic gap match, associate, graphic order, slider, drawing, upload, media and custom interactions. The agent cannot create or convert to them; the manifest does not list them.',
  '- **Select point**: `areaMappings`, image source and size are edited through the image tooling, not by the agent. Only `maxChoices`, `minChoices`, `correctResponse` and `score` are operations.',
  '- **Structural child edits** (adding or removing choices, gaps, hottexts, match sets) go through `insert` / `replace` of validated HTML, not through attribute operations. Identifiers on replacements must be preserved.',
  '- **General-purpose shared vocabulary** (layout rows and columns, alignment, writing mode, `qti-keyword-emphasis`) is content, not an attribute operation; it is emitted inside generated HTML and validated through the schema.',
  '- **Rendering caveats**: `qti-counter-up` / `qti-counter-down` are preserved and exported but no pinned component styles them. `orientation` on order interactions has both an attribute and a vocabulary group; the vocabulary group is preferred and the attribute is dropped from HTML when the class is present.',
  "- **Two match representations**: `qtiMatchInteraction` and `qtiMatchInteractionTabular` both serialize to `qti-match-interaction`; the tabular node is the editor's table form and carries `dataFirstColumnHeader`.",
  ''
];

const output = lines.join('\n');
if (check) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) {
    console.error('docs/ai-support-matrix.md is stale; run `pnpm ai:matrix`.');
    process.exit(1);
  }
  console.log('docs/ai-support-matrix.md is up to date');
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target} (${interactions.length} interactions, ${children.length} child node types)`);
}
